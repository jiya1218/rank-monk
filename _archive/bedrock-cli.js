#!/usr/bin/env node
/**
 * Rank Monk - Direct AWS Bedrock CLI
 * Uses your active Bedrock API Key with Amazon Nova Pro (amazon.nova-pro-v1:0)
 * 
 * Commands:
 *   node bedrock-cli.js test
 *   node bedrock-cli.js blog "Autonomous Organic SEO in 2026"
 *   node bedrock-cli.js svg "Zen monk meditating on futuristic mountain"
 */

const fs = require('fs');
const path = require('path');
const { BedrockRuntimeClient, ConverseCommand } = require('@aws-sdk/client-bedrock-runtime');

// 1. Read Bedrock credentials from .env
let token = process.env.AWS_BEARER_TOKEN_BEDROCK || process.env.VITE_BEDROCK_API_KEY;
if (!token && fs.existsSync('.env')) {
  const envContent = fs.readFileSync('.env', 'utf8');
  const match = envContent.match(/AWS_BEARER_TOKEN_BEDROCK=([^\s\r\n]+)/) || envContent.match(/VITE_BEDROCK_API_KEY=([^\s\r\n]+)/);
  if (match) token = match[1].replace(/['"]/g, '');
}

if (!token && fs.existsSync('bedrock-long-term-api-key.csv')) {
  const csv = fs.readFileSync('bedrock-long-term-api-key.csv', 'utf8');
  const lines = csv.split('\n');
  if (lines[1]) token = lines[1].split(',')[1]?.trim();
}

if (!token) {
  console.error('❌ Error: No Bedrock token found in .env or bedrock-long-term-api-key.csv');
  process.exit(1);
}

process.env.AWS_BEARER_TOKEN_BEDROCK = token;
const client = new BedrockRuntimeClient({ region: 'us-east-1' });
const MODEL_ID = 'amazon.nova-pro-v1:0';

// 2. Parse Commands
const command = (process.argv[2] || 'test').toLowerCase();
const topic = process.argv.slice(3).join(' ') || 'The Future of Autonomous AI SEO in 2026';

console.log('====================================================');
console.log('🧘 RANK MONK - DIRECT AWS BEDROCK ENGINE');
console.log(`Model:  ${MODEL_ID} (AWS Bedrock us-east-1)`);
console.log(`Auth:   Bearer Key ${token.slice(0, 10)}...${token.slice(-6)}`);
console.log('====================================================');

async function execute() {
  if (command === 'test') {
    console.log('\nTesting connection to AWS Bedrock...');
    const start = Date.now();
    try {
      const cmd = new ConverseCommand({
        modelId: MODEL_ID,
        messages: [{ role: 'user', content: [{ text: 'Respond with a 2-sentence confirmation that Rank Monk Bedrock API is live and active.' }] }],
        inferenceConfig: { maxTokens: 100, temperature: 0.5 }
      });
      const res = await client.send(cmd);
      const latency = Date.now() - start;
      console.log(`\n✅ AWS BEDROCK RESPONDED IN ${latency}ms!`);
      console.log('HTTP Status:', res.$metadata.httpStatusCode);
      console.log('Input Tokens: ', res.usage?.inputTokens);
      console.log('Output Tokens:', res.usage?.outputTokens);
      console.log('\nModel Response:');
      console.log(res.output?.message?.content?.[0]?.text);
      console.log('\n====================================================\n');
    } catch (err) {
      console.error('❌ Bedrock Error:', err.message);
    }
    return;
  }

  if (command === 'blog') {
    console.log(`\nGenerating full autonomous blog article for: "${topic}"...`);
    const start = Date.now();
    try {
      const prompt = `You are the lead technical growth strategist for Rank Monk OS.
Write a comprehensive, publication-ready, 1200+ word Markdown blog post about: "${topic}".
Include:
- Compelling H1 Title
- Executive Summary
- 4 Detailed H2/H3 Sections with real benchmarks, architectural diagrams in ASCII, and tactical frameworks
- AEO & GEO (Generative Engine Optimization) insights
- Conclusion and Action Checklist

Format in clean GitHub Flavored Markdown.`;

      const cmd = new ConverseCommand({
        modelId: MODEL_ID,
        messages: [{ role: 'user', content: [{ text: prompt }] }],
        inferenceConfig: { maxTokens: 4000, temperature: 0.7 }
      });

      const res = await client.send(cmd);
      const latency = Date.now() - start;
      const content = res.output?.message?.content?.[0]?.text || '';

      const outDir = path.join(__dirname, 'generated_articles');
      if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

      const safeSlug = topic.toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 40);
      const filename = `bedrock_blog_${safeSlug}_${Date.now()}.md`;
      const filePath = path.join(outDir, filename);

      fs.writeFileSync(filePath, content, 'utf8');

      console.log(`\n✅ SUCCESS: Full Article Generated by AWS Bedrock!`);
      console.log(`📁 File Saved:    ${filePath}`);
      console.log(`📊 Word Count:    ~${content.split(/\s+/).length} words`);
      console.log(`⏱️ Latency:       ${(latency / 1000).toFixed(2)}s`);
      console.log(`🎟️ Tokens Billed: ${res.usage?.inputTokens} in / ${res.usage?.outputTokens} out`);
      console.log('====================================================\n');
    } catch (err) {
      console.error('❌ Bedrock Error:', err.message);
    }
    return;
  }

  if (command === 'svg') {
    console.log(`\nGenerating real vector SVG visual for: "${topic}" using AWS Bedrock...`);
    const start = Date.now();
    try {
      const prompt = `Generate a clean, modern, professional vector SVG graphic for: "${topic}".
Use the Rank Monk palette: slate navy (#111c26, #1e2d3c), warm gold (#c49866, #b98b6a), and crisp accents.
Include smooth gradients, glowing drop-shadows, and elegant geometry.
Return ONLY valid <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 800" ...>...</svg> XML code. No explanation text, just the raw SVG code.`;

      const cmd = new ConverseCommand({
        modelId: MODEL_ID,
        messages: [{ role: 'user', content: [{ text: prompt }] }],
        inferenceConfig: { maxTokens: 4000, temperature: 0.7 }
      });

      const res = await client.send(cmd);
      const latency = Date.now() - start;
      const text = res.output?.message?.content?.[0]?.text || '';
      const svgMatch = text.match(/<svg[\s\S]*<\/svg>/i);

      if (!svgMatch) {
        throw new Error('Model did not return valid SVG markup.');
      }

      const outDir = path.join(__dirname, 'generated_images');
      if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

      const safeSlug = topic.toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 30);
      const filename = `bedrock_vector_${safeSlug}_${Date.now()}.svg`;
      const filePath = path.join(outDir, filename);

      fs.writeFileSync(filePath, svgMatch[0], 'utf8');

      console.log(`\n✅ SUCCESS: Real Vector SVG Generated by AWS Bedrock!`);
      console.log(`📁 File Saved:    ${filePath}`);
      console.log(`📦 Size:          ${(fs.statSync(filePath).size / 1024).toFixed(1)} KB`);
      console.log(`⏱️ Latency:       ${(latency / 1000).toFixed(2)}s`);
      console.log(`🎟️ Tokens Billed: ${res.usage?.inputTokens} in / ${res.usage?.outputTokens} out`);
      console.log('====================================================\n');
    } catch (err) {
      console.error('❌ Bedrock Error:', err.message);
    }
    return;
  }

  if (command === 'google' || command === 'gemma') {
    const googleModel = 'google.gemma-3-27b-it';
    console.log(`\nQuerying Google's flagship model on Bedrock (${googleModel})...`);
    console.log(`Prompt: "${topic}"`);
    const start = Date.now();
    try {
      const cmd = new ConverseCommand({
        modelId: googleModel,
        messages: [{ role: 'user', content: [{ text: topic }] }],
        inferenceConfig: { maxTokens: 2000, temperature: 0.7 }
      });
      const res = await client.send(cmd);
      const latency = Date.now() - start;
      const text = res.output?.message?.content?.[0]?.text || '';
      console.log(`\n✅ GOOGLE GEMMA 3 RESPONDED IN ${(latency / 1000).toFixed(2)}s!`);
      console.log('HTTP Status: 200');
      console.log(`Tokens:  ${res.usage?.inputTokens} in / ${res.usage?.outputTokens} out`);
      console.log('\n--- Google Model Output: ---');
      console.log(text);
      console.log('\n====================================================\n');
    } catch (err) {
      console.error('❌ Google Bedrock Error:', err.message);
    }
    return;
  }

  console.log('Unknown command. Use: test | blog | svg | google');
}

execute();
